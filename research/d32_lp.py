"""C5VRX by Twotoz/contributors: exact D32-R2 post-detection counter LP.

Extends u85q_lp.py's two-bundle generator, not the retired live-switch policy.
D32's token ignores sample B. Zeroing raw address bits 8/9 prevents the
address/phase carry that dithers historical U85Q-LP's filter. Same D32 LUT.
Usage: python research/d32_lp.py generate
       IDF_PATH=... python test/test_d32_lp.py
       python research/d32_lp_study.py [output.json]
Host evidence only; physical FIFO, timing and colour acceptance are pending.
"""
from pathlib import Path
import sys
import numpy as np
from numba import njit
import sim
import u85q_lp

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'main/d32_lp.bsasm'


def generate(write=True):
    table = sim.u85q_lut(ROOT / 'main/d32.bsasm')
    # This property is specific to D32: do not apply to arbitrary U85Q LUTs.
    tokens = table.astype(np.int64) >> 11
    assert np.array_equal(tokens, np.tile(tokens[:256], 4))
    body = u85q_lp.program(raw_bits='4 5 6 7 0 1 2 3 L L'.split())
    text = ('# C5VRX by Twotoz/contributors: experimental D32-R2-LP.\n'
            '# Generated by research/d32_lp.py using u85q_lp.program.\n'
            '# Exact y=(y>>1)+(x>>1); D32 ignores sample B, so raw address\n'
            '# bits 8/9 are zero: no fractional address/phase carry into y.\n'
            '# A[15:10]=y; controller LDCTIA, worker ADDCTIAH.\n'
            '# Phase and previous DAC travel through O[6:15]; no DAC pins there.\n'
            '# One extra 50 ns span of latency; [y,y] at TX40; reset y=0.\n'
            'cfg prefetch true\ncfg eof_on downstream\ncfg trailing_bytes 0\ncfg lut_width_bits 16\n'
            + body + 'lut ' + ' '.join(str(int(v)) for v in table) + '\n')
    if write:
        OUT.write_text(text)
    return text


@njit(cache=True)
def filter_codes(codes):
    """Independent integer IIR on the stock DAC20 stream, extra pair delay.

    Both terms truncate separately. No saturation needed: 0..63 -> 0..62.
    The zero output pair at reset precedes filtering stock's initial zero.
    """
    out = np.zeros(len(codes), np.uint8)
    y = 0
    for k in range(0, len(codes) - 2, 2):
        y = (y >> 1) + (int(codes[k]) >> 1)
        out[k + 2] = y
        out[k + 3] = y
    return out


def codes(raw, table=None):
    if table is None:
        table = sim.u85q_lut(ROOT / 'main/d32.bsasm')
    return filter_codes(sim._pair_codes(raw, table, sim.PAIR_BITS, 5))


if __name__ == '__main__':
    if sys.argv[1:] == ['generate']:
        generate()
    else:
        print(__doc__)
        sys.exit(2)
