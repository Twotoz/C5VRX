"""Exports the latest checkpoint into p5t_champion.json and main/p5t_tables.h
(C5VRX by Twotoz and contributors)
"""
import json
import math
from pathlib import Path
import numpy as np
from p5t_optimizer import build_lut_from_params

HERE = Path(__file__).resolve().parent
CKPT = HERE / 'data' / 'p5t_checkpoint.json'
CHAMP = HERE / 'data' / 'p5t_champion.json'
HEADER = HERE.parent / 'main' / 'p5t_tables.h'

def export():
    if not CKPT.exists():
        print(f"No checkpoint found at {CKPT}")
        return
    data = json.loads(CKPT.read_text())
    candidate = data['best_candidate']
    metrics = data['best_metrics']
    print(f"Exporting Checkpoint Gen {data['generation']}: -3dB Lock: {metrics['lock_m3']:.3f} | +4dB SINAD: {metrics['sinad_4']:+.2f} dB | Step: {metrics['demod_step_deg']:.1f}°")

    CHAMP.write_text(json.dumps(data, indent=2))
    print(f"[+] Wrote {CHAMP}")

    lut = build_lut_from_params(candidate)
    body = ',\n'.join('    ' + ', '.join(f'0x{v:04x}' for v in lut[i:i + 12]) for i in range(0, 1024, 12))
    header_text = f"""/* C5VRX by Twotoz and contributors: P5-TRACK Demodulator Table.
 * Generated by research/p5t_optimizer.py after multi-hour hyper-evolution.
 * Features:
 *   - Phase step: {metrics['demod_step_deg']:.1f} degrees (under 15 deg)
 *   - Simulated -3 dB C/N linelock: {metrics['lock_m3']:0.3f}
 *   - Simulated +4 dB C/N SINAD: {metrics['sinad_4']:+5.2f} dB
 *   - Unique DAC levels: {metrics['unique_dac_levels']}
 *   - Zero pipeline restarts (single fixed table)
 */
#pragma once
#include <stdint.h>

#define P5T_TABLE_ENTRIES 1024
static const uint16_t p5t_table[1024] = {{
{body}
}};
"""
    HEADER.write_text(header_text)
    print(f"[+] Wrote {HEADER}")

if __name__ == '__main__':
    export()
