"""C5VRX by Twotoz and the C5VRX contributors: U50P64-R1, a range decoder for
low and nominal deviation VTXs.

Extends U80P64-R1 (p64_model.py, PR #250 and its repair, docs/P64.md) and the
retired kp ladder (research/legacy_demod, FINDINGS "PR #196 ladder": a lower
loop gain was worth 1.6-3.35 dB in simulation for a narrow VTX). Same program,
same Q4/I4 RX40 input, two LUT16 lookups per 50 ns, 64 states, unique CVBS20
as [D,D] at TX40; only the table differs: the video and sync loop gains are
0.50 instead of 0.80 / 0.60. Untrained: the U80P64-R1 formulas with two
changed constants, no fitted entry.

A loop gain of 0.5 is a one-pole low-pass on the recovered frequency (-3 dB
near 2.3 MHz at 20 MS/s; the colour subcarrier ~5-6 dB down) and follows a
phase advance of at most pi/2 per 50 ns (5 MHz) before it slips, so it suits
deviation <= ~1.0 only. Host model (u50p64_validation.json, fresh seeds):
luma SINAD +2.0..2.7 dB at deviation 0.7 for C/N 0-9 dB with the same line
lock, +0.9..1.6 dB at 1.0, a loss from 1.2 (-4..-8 dB at 1.4); at deviation
0.6 the lock dipped at one point (0.80 against 0.99 at 2 dB). It trades fine
detail and colour level for range; selectable (menu DEMOD, console m), never
automatic, U80P64-R1 stays the default.

    python research/u50p64.py --write      regenerate table header and program
    python research/u50p64.py --check      header and program are current; transfer gates
    python research/u50p64.py --validate   rewrite research/data/u50p64_validation.json

Simulation only: no picture, colour, range or goggle result is claimed.
"""
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import p64_model  # noqa: E402
import sim  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MODEL_ID = 'U50P64-R1'
HEADER = ROOT / 'main/u50p64_table.h'
PROGRAM = ROOT / 'main/u50p64.bsasm'
VALIDATION = ROOT / 'research/data/u50p64_validation.json'
TONE_MHZ = (-4.0, 4.0)   # clean-tone transfer gate; beyond ~5 MHz the loop slips by design


def params():
    p = dict(json.loads((ROOT / 'research/data/p64_repair.json').read_text())['params'])
    p['kp_vid'] = 0.5
    p['kp_sync'] = 0.5
    return p


def table():
    return p64_model.build_lut64_from_params(params())


def digest(t):
    return hashlib.sha256(struct.pack('<1024H', *(int(v) for v in t))).hexdigest()


def header_text(t):
    rows = [', '.join(f'0x{int(v):04x}' for v in t[k:k + 12]) for k in range(0, 1024, 12)]
    return f'''/* C5VRX by Twotoz/contributors: {MODEL_ID}, the U80P64-R1 formulas with loop
 * gain 0.50 (video and sync): a range decoder for deviation <= ~1.0.
 * Generated by research/u50p64.py; never edit by hand. Host-checked only.
 */
#pragma once
#include <stdint.h>
#define U50P64_MODEL_ID "{MODEL_ID}"
#define U50P64_TABLE_SHA256 "{digest(t)}"
static const uint16_t u50p64_table[1024] = {{
    {(',' + chr(10) + '    ').join(rows)}
}};
'''


def program_text(t):
    """The U80P64-R1 program with this table: identical instructions."""
    source = (ROOT / 'main/p64.bsasm').read_text()
    lines = source.splitlines()
    out, replaced = [], 0
    for k, line in enumerate(lines):
        if k == 0:
            out.append(f'# C5VRX by Twotoz/contributors: {MODEL_ID}. The U80P64-R1 program (main/p64.bsasm) with the '
                       f'loop-gain 0.50 table; generated by research/u50p64.py.')
        elif line.startswith('lut '):
            out.append('lut ' + ' '.join(str(int(v)) for v in t))
            replaced += 1
        else:
            out.append(line)
    assert replaced == 1
    return '\n'.join(out) + '\n'


def raw_tone(mhz, radius, phase, n=8000):
    k = np.arange(n)
    z = radius * np.exp(2j * np.pi * mhz * 1e6 * k / 40e6 + 1j * phase)
    return (((np.floor(z.real).astype(np.int64) & 15) << 4) | (np.floor(z.imag).astype(np.int64) & 15)).astype(np.uint8)


def gates(t):
    """Transfer gates of test_p64.py on the band this decoder is for."""
    worst = 0.0
    for radius in (2.0, 4.0, 6.0):
        for phase in (0.27, 1.1, 2.7, -2.1):
            for mhz in np.arange(TONE_MHZ[0], TONE_MHZ[1] + 0.01, 0.25):
                codes = sim._pair_codes(raw_tone(mhz, radius, phase), t, sim.PAIR_BITS, 4)[1000:]
                error = abs(float(codes.mean()) - (mhz + 6.0) / 15.0 * 63.0)
                worst = max(worst, error)
                assert error < 0.5, (radius, phase, mhz, float(codes.mean()))
    # Sync to porch of a deviation-1.0 VTX: the porch is reached within 1 us.
    freq = np.r_[np.full(2000, -2.9e6), np.full(4000, -1e6)]
    for radius in (2.0, 4.0, 6.0):
        for phase in (0.27, 1.1, 2.7, -2.1):
            z = radius * np.exp(2j * np.pi * np.cumsum(freq) / 40e6 + 1j * phase)
            raw = (((np.floor(z.real).astype(np.int64) & 15) << 4) |
                   (np.floor(z.imag).astype(np.int64) & 15)).astype(np.uint8)
            porch = sim._pair_codes(raw, t, sim.PAIR_BITS, 4)[2040:-8]
            mean = np.convolve(porch, np.ones(32) / 32, mode='valid')
            assert np.max(np.abs(mean - 21)) < 0.5, (radius, phase, float(np.max(np.abs(mean - 21))))
    reachable = {0}
    while True:
        more = reachable | {(int(t[s * 16 + k]) >> 6) & 63 for s in reachable for k in range(16)}
        if more == reachable:
            break
        reachable = more
    assert len(reachable) == 64
    # Same token (input) bits as U80P64-R1: the program's first lookup is unchanged.
    assert np.array_equal(t >> 12, p64_model.repaired_table() >> 12)
    return worst


def validate():
    import p5t_eval
    r1 = p64_model.repaired_table()
    t = table()
    rows = []
    for dev in (0.6, 0.7, 0.85, 1.0, 1.2, 1.4):
        for cn in (-2, 0, 2, 4, 6, 9, 12, 20):
            acc = {'U80P64-R1': [], MODEL_ID: []}
            for std, seed in (('NTSC', 7301), ('PAL', 7302), ('NTSC', 7303), ('PAL', 7304)):
                c = sim.make_case(seed, cn, std, dev, filter_hz=12e6, fields=1, physical_adc=True, adc_gain=3.0)
                c['hs0'] = p5t_eval.hs0_of(c['truth'])
                for name, lut in (('U80P64-R1', r1), (MODEL_ID, t)):
                    s = p5t_eval.score_codes(c, sim._pair_codes(c['raw'], lut, sim.PAIR_BITS, 4),
                                             sim._pair_codes(c['clean'], lut, sim.PAIR_BITS, 4))
                    acc[name].append((float(s['lock']), float(s['sinad'])))
            rows.append({'deviation': dev, 'cn_db_20mhz': cn,
                         **{name: {'lock': round(float(np.mean([x[0] for x in v])), 3),
                                   'sinad_db': round(float(np.mean([x[1] for x in v])), 2)} for name, v in acc.items()}})
            print(rows[-1], flush=True)
    VALIDATION.write_text(json.dumps({
        'evidence': 'host simulation only (sim.py physical-ADC model, 12 MHz filter, ADC gain 3, goggle model of '
                    'p5t_eval); no board, picture, colour or range result',
        'model': MODEL_ID, 'table_sha256': digest(t), 'seeds': [7301, 7302, 7303, 7304],
        'selection_seeds': [5101, 5102, 5103, 5104], 'standards': ['NTSC', 'PAL'], 'rows': rows}, indent=1) + '\n')


def main():
    t = table()
    if '--write' in sys.argv:
        HEADER.write_text(header_text(t))
        PROGRAM.write_text(program_text(t))
    if '--validate' in sys.argv:
        validate()
    if '--check' in sys.argv or '--write' in sys.argv:
        assert HEADER.read_text() == header_text(t), 'main/u50p64_table.h is stale: python research/u50p64.py --write'
        assert PROGRAM.read_text() == program_text(t), 'main/u50p64.bsasm is stale: python research/u50p64.py --write'
        got = [int(v, 16) for v in re.findall(r'0x[0-9a-f]{4}', HEADER.read_text().split('u50p64_table[1024]')[1])]
        assert got == [int(v) for v in t]
        worst = gates(t)
        if VALIDATION.exists():
            assert json.loads(VALIDATION.read_text())['table_sha256'] == digest(t), 'validation belongs to another table'
        print(f'PASS: {MODEL_ID} header, program and transfer gates (worst tone error {worst:.2f} code, sha256 {digest(t)[:12]})')


if __name__ == '__main__':
    main()
