"""C5VRX by Twotoz/contributors: full-Q4/I4 PAIR80 counter experiment.

Extends the project's Phase8 HR/PR90 counter work and U85Q-LP's high-byte
operand routing. One raw-byte phase lookup and one counter operation per
instruction. Every IQ sample participates in a nonoverlapping adjacent
pair: IQ80 -> 40 million 12.5-ns slopes/s -> duplicate DAC bytes at TX80.
This is not an all-adjacent 80-million-output discriminator. Outside its
explicit frequency window the six-bit result wraps; it does not clamp.
"""
import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
PERIOD = 320
BIAS = 24
HOLD40_BIAS = 32
TARGET = ROOT / "main/rx80_counter.bsasm"
HEADER = ROOT / "main/rx80_counter_table.h"


def phase(raw, period=PERIOD):
    i, q = raw >> 4, raw & 15
    i = (i if i < 8 else i - 16) + 31.5 / 64
    q = (q if q < 8 else q - 16) + 31.5 / 64
    return round(math.atan2(q, i) * period / math.tau) & 255


def table(period=PERIOD, bias=BIAS):
    return [phase(raw,period) | (((bias-phase(raw,period)) & 255) << 8)
            for _bank in range(4) for raw in range(256)]


def source(period=PERIOD, mhz=80, hold40=False):
    blocks = []
    for slot in range(4):
        blocks.append(f"""add_{slot}:
    set 16..23 0..7,
    set 24..31 L0..L7,
    read 8,
    addctiah
load_emit_{slot}:
    set 0..5 A8..A13,
    set 8..13 A8..A13,
    set 16..23 {"8..15" if hold40 else "0..7"},
    set 24..31 L8..L15,
    read 8,
    write 16,
    ldctiah
""")
    # Lookup sequence raw0,raw2,raw2,raw4,... when source-held40 is selected.
    return (f"# C5VRX by Twotoz/contributors: experimental PAIR{mhz}{'-H40' if hold40 else ''}-C{period}{'-B32' if hold40 else ''}.\n" +
            (f"# IQ80 capture, observed held40 source; overlapping 25-ns slopes, unique40 at TX80.\n" if hold40 else
             f"# Full IQ{mhz}; paired adjacent slopes at CVBS{mhz//2}, duplicate TX{mhz}.\n") +
            "# Shared raw-angle LUT replicated across four high-operand banks.\n" +
            ("# Counter output wraps outside [-5,+4.84375] MHz; bench only.\n" if hold40 else
             "# Counter output wraps outside [-6,+9.75] MHz; bench only.\n") +
            "cfg prefetch true\ncfg eof_on downstream\ncfg trailing_bytes 0\n"
            "cfg lut_width_bits 16\nlut " + " ".join(map(str, table(period,HOLD40_BIAS if hold40 else BIAS))) +
            "\n\n" + "\n".join(blocks))


def generate():
    TARGET.write_text(source(), encoding="utf-8")
    values = [phase(raw) for raw in range(256)]
    sha = hashlib.sha256(b"".join(x.to_bytes(2, "little") for x in table())).hexdigest()
    HEADER.write_text(
        "/* C5VRX by Twotoz/contributors; generated by research/rx80_counter.py. */\n"
        "#pragma once\n#include <stdint.h>\n"
        f'#define RX80_COUNTER_MODEL "PAIR80-C320"\n#define RX80_COUNTER_BIAS {BIAS}u\n#define RX80_HOLD40_BIAS {HOLD40_BIAS}u\n'
        f'#define RX80_COUNTER_SHA "{sha}"\n'
        "static const uint8_t rx80_counter_phase[256] = {\n" +
        "\n".join("    " + ", ".join(map(str, values[k:k+16])) + ","
                  for k in range(0, 256, 16)) + "\n};\n" +
        "static const uint8_t rx80_hold40_phase[256] = {\n" +
        "\n".join("    " + ", ".join(str(phase(raw,256)) for raw in range(k,k+16)) + ","
                  for k in range(0,256,16)) + "\n};\n", encoding="utf-8")
    print(f"generated {TARGET.name}; LUT SHA256={sha}")
    (ROOT/"main/rx48_counter.bsasm").write_text(source(192,48),encoding="utf-8")
    (ROOT/"main/rx80_hold40.bsasm").write_text(source(256,80,True),encoding="utf-8")


def emulate(data, n_out, period=PERIOD, mhz=80, hold40=False):
    """IDF-assembled mux/opcode emulator, adapted from C5VRX U85Q-LP."""
    idf = Path(os.environ["IDF_PATH"])
    sys.path.insert(0, str(idf / "tools"))
    import bsasm
    cfg = json.loads((idf / "components/esp_driver_bitscrambler/bsasm_targets/esp32c5.json").read_text())
    insts, meta, lut = bsasm.bsasm_assemble(bsasm.bsasm_parse(source(period,mhz,hold40)), cfg)
    assert len(insts) == 8 and meta["lut_width_bits"] == 16
    stream = iter(data)
    def take(n):
        return sum(next(stream) << (8*k) for k in range(n//8))
    reg = take(64)
    previous = look = counter = pc = executed = 0
    emitted = bytearray()
    while len(emitted) < n_out:
        inst = insts[pc]
        flags = {}
        for src in inst["mux"].values():
            flags.update({k: v for k, v in src.get("flags", {}).items() if k != "rel_addr"})
        out = 0
        for bit, src in inst["mux"].items():
            index = src["muxsel"]
            if index < 32:
                value = reg >> index
            elif index < 64:
                if flags.get("lutsel") and index >= 48:
                    value = look >> (index-48)
                elif flags.get("ctrsel"):
                    assert index < 48, "counter B is not used"
                    value = counter >> (index-32)
                else:
                    value = reg >> index
            elif index in (94, 95):
                value = index-94
            elif 96 <= index < 128:
                value = previous >> (index-96)
            else:
                raise AssertionError(index)
            out |= (value & 1) << bit
        op = inst["op"]
        assert op["op"] == (bsasm.OP_ADDCTI if pc % 2 == 0 else bsasm.OP_LDCTI)
        assert op["h"] and not op["l"] and op["c"] == 0
        operand = (out >> 24) & 255
        hi = ((counter >> 8) + operand if pc % 2 == 0 else operand) & 255
        counter = hi << 8
        write = inst.get("write", 0)
        assert inst["read"] == 8 and write == (16 if pc % 2 else 0)
        emitted.extend((out & ((1 << write)-1)).to_bytes(write//8, "little"))
        reg = (reg >> 8) | (take(8) << 56)
        look = lut[(out >> 16) & 1023]
        previous = out
        executed += 1
        pc = (pc+1) % 8
    assert executed == len(emitted), "one instruction per input/output byte"
    return emitted


def check():
    for period,mhz in ((320,80),(192,48)):
        target=ROOT/f'main/rx{mhz}_counter.bsasm'
        assert target.read_text() == source(period,mhz), "regenerate assembly"
        lut = table(period)
        for bank in range(4):
            assert lut[bank*256:(bank+1)*256] == lut[:256]
        raw = bytearray()
        expected = bytearray(b"\0\0")  # startup pair is not trusted
        for a in range(256):
            for b in range(256):
                raw.extend((a, b))
                code = (phase(b,period)-phase(a,period)+BIAS) & 63
                expected.extend((code, code))
        raw.extend(b"\0"*16)
        got = emulate(raw, len(expected),period,mhz)
        assert got[2:] == expected[2:], "assembled program differs from independent pair reference"
        print(f"PASS: IQ{mhz}, all 65,536 full-Q4/I4 pairs, 8 slots, read8 every instruction")
    assert (ROOT/'main/rx80_hold40.bsasm').read_text()==source(256,80,True)
    endpoints=bytearray()
    for a in range(256):
        for b in range(256): endpoints.extend((a,b))
    expected=bytearray(b'\0\0')
    for a,b in zip(endpoints,endpoints[1:]):
        c=(phase(b,256)-phase(a,256)+HOLD40_BIAS)&63
        expected.extend((c,c))
    for alignment in (0,1):
        raw=bytearray(v for x in endpoints for v in (x,x))
        if alignment: raw=raw[1:]+raw[-1:]
        raw.extend(b'\0'*16)
        got=emulate(raw,len(expected),256,80,True)
        assert got[2:]==expected[2:], f'held40 alignment {alignment}'
    print('PASS: held40, all 65536 endpoint pairs, both duplicate alignments, actual assembled mux/opcodes')


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("action", choices=("generate", "check"))
    args = ap.parse_args()
    generate() if args.action == "generate" else check()
