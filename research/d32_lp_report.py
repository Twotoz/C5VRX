"""C5VRX/Twotoz: render committed D32-R2-LP results without rerunning IQ."""
import json
from pathlib import Path
import numpy as np
from d32_lp_study import CNRS, DEVIATIONS
ROOT=Path(__file__).resolve().parents[1]
NAMES=('D32-R2','D32-R2-LP','U50P64-R1')


def render():
    data=json.loads((ROOT/'research/data/d32_lp.json').read_text())
    rows=data['rows']
    assert len(rows)==240
    def group(s,d,c):
        return [r for r in rows if r['standard']==s and r['deviation']==d and r['cnr_db']==c]
    def mean(rs,n,k):
        return float(np.mean([r['decoders'][n][k] for r in rs]))
    def values(rs,k,fmt='.2f'):
        return ' / '.join(format(mean(rs,n,k),fmt) for n in NAMES)
    def threshold(s,d,n,colour=False):
        for c in CNRS:
            rs=[r['decoders'][n] for r in rows if r['standard']==s and r['deviation']==d and r['cnr_db']>=c]
            if all(r['usable'] and (not colour or not r['colour_killer_risk']) for r in rs):
                return str(c)
        return 'none'
    text=['# D32-R2-LP simulated results','',
          'C5VRX by Twotoz and the C5VRX contributors. Synthetic host results only.',
          'Generated by `python research/d32_lp_report.py` from [raw metrics](../research/data/d32_lp.json).',
          'See [architecture, definitions and limitations](D32_LP.md) before interpreting these numbers.','',
          'Every cell with three values is **D32-R2 / D32-R2-LP / U50P64-R1**, mean of three seeds.',
          'U50 is deliberately run without its production U80 fallback (deviations 1.4/1.7 are outside its intended envelope).','',
          '## Usable threshold on the sampled C/N grid','',
          'Lowest C/N where every seed passes at this and every higher sampled C/N. No interpolation or range claim.',
          'Usable: lock >= 0.9 and 2 MHz luma SINAD >= 6 dB. Colour-safe additionally passes the declared killer proxy.','',
          '| Standard | Deviation | Usable C/N dB (D32 / LP / U50) | Colour-safe C/N dB (D32 / LP / U50) |',
          '| --- | --- | --- | --- |']
    for s in ('NTSC','PAL'):
        for d in DEVIATIONS:
            text.append(f'| {s} | {d:.1f} | '+ ' / '.join(threshold(s,d,n) for n in NAMES)+' | '+' / '.join(threshold(s,d,n,True) for n in NAMES)+' |')
    text+=['','## Full C/N sweep','',
           '| Standard | Dev | C/N dB | Luma SINAD dB | Composite SINAD dB | Picture lock | Sync integrity | Burst gain dB | Killer-risk fraction |',
           '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for s in ('NTSC','PAL'):
        for d in DEVIATIONS:
            for c in CNRS:
                rs=group(s,d,c)
                text.append(f'| {s} | {d:.1f} | {c} | '+' | '.join(values(rs,k) for k in
                            ('luma_sinad_db','composite_sinad_db','picture_lock','sync_integrity','burst_gain_db','colour_killer_risk'))+' |')
    text+=['','## Strong signal and sync detail (C/N 30 dB)','',
           'Clean detail is RMS gain in 2.5–5 MHz after the same per-decoder clean affine calibration.',
           'It includes chroma. Burst amplitude is a coherent inter-line phasor fit in calibrated IRE.','',
           '| Standard | Dev | Clean detail gain dB | Clean detail error IRE | Burst amplitude IRE | Burst phasor SNR dB | Sync depth IRE | Sync width MAE µs |',
           '| --- | --- | --- | --- | --- | --- | --- | --- |']
    for s in ('NTSC','PAL'):
        for d in DEVIATIONS:
            rs=group(s,d,30)
            width=' / '.join('n/a' if any(r['decoders'][n]['sync_width_mae_us'] is None for r in rs) else f"{mean(rs,n,'sync_width_mae_us'):.3f}" for n in NAMES)
            text.append(f'| {s} | {d:.1f} | '+' | '.join(values(rs,k) for k in
                        ('clean_detail_gain_db','clean_detail_error_ire','burst_ire','burst_snr_db','sync_depth_ire'))+f' | {width} |')
    text+=['','## Largest individual regressions versus stock D32-R2','',
           '| Metric | LP minus stock | Standard | Deviation | C/N dB | Seed |',
           '| --- | --- | --- | --- | --- | --- |']
    for k in ('luma_sinad_db','composite_sinad_db','picture_lock','sync_integrity','burst_gain_db'):
        r=min(rows,key=lambda r:r['decoders']['D32-R2-LP'][k]-r['decoders']['D32-R2'][k])
        delta=r['decoders']['D32-R2-LP'][k]-r['decoders']['D32-R2'][k]
        text.append(f"| {k} | {delta:.4f} | {r['standard']} | {r['deviation']:.1f} | {r['cnr_db']} | {r['seed']} |")
    return '\n'.join(text)+'\n'


if __name__=='__main__':
    (ROOT/'docs/D32_LP_RESULTS.md').write_text(render())
