"""C5VRX by Twotoz/contributors: U55P64-K1, U80P64-R1 with a kneed loop gain.

Extends the U80P64-R1 table (research/p64_model.py, PR #250 repair). Same
64 phase states, 16 tokens, LUT16 layout and two lookups per pair; only the
video-state update law changes. A phase error up to the knee (45 degrees)
moves the tracker with gain 0.55 instead of 0.80, so single-sample 4-bit
phase outliers move it less (fewer coloured dots / sparkles); the part of
the error beyond the knee uses gain 0.95, and a +0.25 rad per 50 ns video
prior keeps fast white (up to +6.5 MHz) tracking. Plain gain 0.70 lost
that: up to 17 codes too low at +6..6.5 MHz.

Host model only: no board, goggle or range result is claimed.
docs/FINDINGS.md "Coloured dots: kneed tracker gain".

Usage: p64_k1.py [check] | write
"""
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

import numpy as np

import p64_model

ROOT = Path(__file__).resolve().parents[1]
MODEL_ID = 'U55P64-K1'
DATA = ROOT / 'research/data/p64_k1.json'
HEADER = ROOT / 'main/p64k1_tables.h'
PROGRAM = ROOT / 'main/p64k1.bsasm'


def params():
    base = json.loads((ROOT / 'research/data/p64_repair.json').read_text())['params']
    base.update(json.loads(DATA.read_text())['changes'])
    return base


def table():
    return p64_model.build_lut64_from_params(params())


def digest(lut):
    return hashlib.sha256(struct.pack('<1024H', *(int(v) for v in lut))).hexdigest()


def checked_in_table():
    text = HEADER.read_text()
    values = text.split('p64k1_table[1024] = {', 1)[1].split('}', 1)[0]
    return np.array([int(v, 16) for v in re.findall(r'0x[0-9a-fA-F]+', values)], dtype=np.uint16)


def render_header(lut):
    rows = ',\n    '.join(', '.join(f'0x{int(v):04x}' for v in lut[k:k + 12]) for k in range(0, 1024, 12))
    return f'''/* C5VRX by Twotoz/contributors: {MODEL_ID}, U80P64-R1 with a kneed loop gain.
 * Generated by research/p64_k1.py from research/data/p64_k1.json.
 * 14 coarse / 50 fine phase states, 16 tokens; bits 0..5 DAC, 6..11 next
 * state, 12..15 token (unchanged layout). Video gain 0.55 up to a 45-degree
 * error, 0.95 beyond it, +0.25 rad prior. Host model only; board test
 * pending. docs/FINDINGS.md "Coloured dots: kneed tracker gain".
 */
#pragma once
#include <stdint.h>
#define P64K1_MODEL_ID "{MODEL_ID}"
#define P64K1_TABLE_ENTRIES 1024
#define P64K1_TABLE_SHA256 "{digest(lut)}"
static const uint16_t p64k1_table[1024] = {{
    {rows}
}};
'''


def render_program(lut):
    """main/p64.bsasm with this table; the instructions stay identical."""
    text = (ROOT / 'main/p64.bsasm').read_text()
    head, rest = text.split('\nlut ', 1)
    rest = rest.split('\n', 1)[1]
    head = (f'# C5VRX by Twotoz/contributors: {MODEL_ID}, the U80P64-R1 program with the kneed-gain table.\n'
            '# Generated by research/p64_k1.py from main/p64.bsasm; do not edit.\n' +
            '\n'.join(head.split('\n')[1:]))
    return head + '\nlut ' + ' '.join(str(int(v)) for v in lut) + '\n' + rest


if __name__ == '__main__':
    lut = table()
    if sys.argv[1:] == ['write']:
        HEADER.write_text(render_header(lut))
        PROGRAM.write_text(render_program(lut))
        print('wrote', HEADER.name, PROGRAM.name, digest(lut))
    else:
        assert np.array_equal(lut, checked_in_table()), 'p64k1_tables.h differs from research/data/p64_k1.json'
        assert PROGRAM.read_text() == render_program(lut), 'p64k1.bsasm differs from the generator'
        print(f'PASS: {MODEL_ID} header and program reproduce ({digest(lut)})')
