"""Generate analytic proposal tables, C5VRX by Twotoz and contributors.

Tables are integration of explicit physical likelihoods, not trained rankings.
Radius/noise hypotheses are illustrative ADC contexts, NOT measured board data.
Regenerate with: OPENBLAS_NUM_THREADS=1 python v5/research/build_lane_shadow.py
"""
from pathlib import Path
import hashlib
import numpy as np
import iq_lane_fusion as F

CONTEXTS = tuple(F.Context((r,), sigma=s) for r in (32., 64., 128., 256.) for s in (8., 24.))
N = 64
UNIT = 1e10                         # one unit = (100 kHz)^2


def build():
    table = np.empty((len(CONTEXTS), len(F.SHADOW_PLANS), 256), np.uint16)
    for c, ctx in enumerate(CONTEXTS):
        current = F.likelihood(F.ULTRA, ctx, N)
        sums = current.sum(axis=1)
        for p, plan in enumerate(F.SHADOW_PLANS):
            next_L = F.likelihood(plan, ctx, N)
            for byte in range(256):
                # Impossible-under-model observation: uniform uncertainty.
                previous = current[byte] / sums[byte] if sums[byte] > 1e-290 else np.full(N, 1 / N)
                risk = F.frequency_risk(previous, next_L, ctx)
                value = int(np.ceil(risk / UNIT))
                if not 0 <= value <= 65535:
                    raise ValueError("risk exceeds firmware encoding")
                table[c, p, byte] = value
        print("integrated context", c, "radius", ctx.radii, "sigma", ctx.sigma, flush=True)
    return table


def render(table):
    digest = hashlib.sha256(table.astype('<u2').tobytes()).hexdigest()
    lines = ["/* C5VRX by Twotoz/contributors; generated by build_lane_shadow.py.",
             " * Analytic model-only proposal grid: radii32/64/128/256, sigma8/24 ADC LSB.",
             " * 64 phases, 40 MS/s, increment support +/-12 MHz, independent Gaussian axes.",
             " * Not calibrated C/N, measured range, or permission to actuate. */", "#pragma once", "#include <stdint.h>",
             '#define IQF_TABLE_SHA256 "' + digest + '"',
             '#define IQF_CONTEXTS 8u', '#define IQF_CANDIDATES 6u', '#define IQF_CURRENT 2u',
             'static const char *const iqf_names[IQF_CANDIDATES] = {' +
             ','.join('"' + p.name + '"' for p in F.SHADOW_PLANS) + '};',
             'static const uint8_t iqf_bits[IQF_CANDIDATES][2][4] = {']
    for plan in F.SHADOW_PLANS:
        lines.append('    {{' + ','.join(map(str, plan.i)) + '},{' + ','.join(map(str, plan.q)) + '}},')
    lines += ['};', 'static const uint16_t iqf_risk[IQF_CONTEXTS][IQF_CANDIDATES][256] = {']
    for context in table:
        lines.append('  {')
        for row in context:
            lines.append('    {' + ','.join(map(str, row)) + '},')
        lines.append('  },')
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / 'main' / 'lane_shadow_table.h'
    content = render(build())
    if args.check:
        if path.read_text() != content:
            raise SystemExit('generated table differs')
    else:
        path.write_text(content)
    print(path, flush=True)
