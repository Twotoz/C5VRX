"""C5VRX by Twotoz/contributors: exact singleton first-EQ selection policy.

Precompute the existing minimum-DAC then phase-distance choice, retaining
ascending-token ties. This changes no waveform or permission to write.
"""
from pathlib import Path
import argparse
import hashlib
import re
from gen_sync_period_bank import cells_for, inputs

ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'main/sync_tip_policy.h'
STEPS=(-9830,-9830,-9830,-9830,-9011,-8602,-7782,-7373)

def generate():
    phase,_,_=inputs()
    cells=cells_for(phase)
    source=(ROOT/'main/kp_tables.h').read_text()
    body=source.split('static const uint16_t kp_tables')[1].split('};',1)[0]
    words=[int(x,16) for x in re.findall(r'0x[0-9a-fA-F]+',body)]
    assert len(words)==8192
    tables=[words[k*1024:(k+1)*1024] for k in range(8)]
    token_cells=[0]*28
    available=0
    for raw in cells:
        address=(raw>>4)|((raw&15)<<4)
        token=tables[0][address]>>11
        if token>=28 or any((tables[0][address|(q<<8)]>>11)!=token for q in (1,2,3)):
            continue
        if not available&(1<<token):token_cells[token]=raw
        available|=1<<token
    assert available
    for table in tables:
        assert all((a>>11)==(b>>11) for a,b in zip(table,tables[0]))
    data=[];minimum=[]
    for level,table in enumerate(tables):
        for state in range(32):
            tokens=[t for t in range(28) if available&(1<<t)]
            lowest=min(table[state*32+t]&63 for t in tokens)
            minimum.append(lowest)
            tied=[t for t in tokens if table[state*32+t]&63==lowest]
            for previous in range(256):
                target=previous+int(STEPS[level]/256)
                token=min(tied,key=lambda t:abs(((phase[token_cells[t]]-target+128)&255)-128))
                data.append(token_cells[token])
    out=['''/* C5VRX by Twotoz/contributors. Generated by tools/gen_sync_tip_policy.py.
 * Exact existing singleton first-EQ choice, not a universal sync waveform.
 * Caller must bind canonical cells, reference LUT, OUTPUT and repair step.
 * Ambiguous decoder-state sets retain the original minimax constructor.
 */
#pragma once
#include <stdint.h>
''', '#define SFW_TIP_POLICY_TABLE_SHA256 "'+hashlib.sha256(source.encode()).hexdigest()+'"\n',
         f'#define SFW_TIP_POLICY_AVAILABLE UINT32_C({available})\n',
         'static const int16_t sfw_tip_policy_steps[8] = {'+','.join(str(s) for s in STEPS)+'};\n']
    for name,values in [('sfw_tip_policy_cells',token_cells),('sfw_tip_policy_minimum',minimum),('sfw_tip_policy_raw',data)]:
        out.append(f'static const uint8_t {name}[{len(values)}] = {{\n')
        for start in range(0,len(values),32):out.append('    '+','.join(str(v) for v in values[start:start+32])+',\n')
        out.append('};\n')
    return ''.join(out)

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    text=generate()
    if args.check:
        if not DEST.exists() or DEST.read_text()!=text:raise SystemExit('stale sync_tip_policy.h')
        print('PASS exact first-EQ policy:65536 ordered singleton choices, canonical tables/cells')
    else:
        DEST.write_text(text);print('wrote',DEST)

if __name__=='__main__':main()
